export function sampleDefaults(row, today) {
  const country = row.countries.find(c => c.code.countryCode && !c.code.restOfWorld);
  const countryCode = country ? country.code.countryCode : '';
  const factors = { KILOGRAMS: 1, GRAMS: 0.001, POUNDS: 0.45359237, OUNCES: 0.028349523125 };
  const upper = row.conditions.filter(c => c.field === 'TOTAL_WEIGHT' && c.operator === 'LESS_THAN_OR_EQUAL_TO');
  const limits = upper.map(c => {
    const factor = factors[c.conditionCriteria.unit];
    if (!factor) throw new Error('Μη υποστηριζόμενη μονάδα βάρους κλίμακας.');
    return c.conditionCriteria.value * factor;
  });
  // DHL accepts kilograms to three decimal places; never exceed the tier upper bound.
  const weight = limits.length ? Math.floor((Math.min(...limits) + 1e-10) * 1000) / 1000 : null;
  const location = countryCode && Object.hasOwn(destinations, countryCode) ? destinations[countryCode] : null;
  return { destinationCountryCode: countryCode, destinationCityName: location ? location.city : '', destinationPostalCode: location ? location.postalCode : '',
    plannedShippingDate: today, weight: weight !== null && weight > 0 ? String(weight) : '', length: '10', width: '10', height: '10' };
}
